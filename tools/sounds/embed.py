#!/usr/bin/env python3
"""Embeds tools/sounds/*.wav into SfxData.kt (base64 chunks, so every platform plays them without resources).

Rerun after changing a clip: python3 tools/sounds/embed.py
"""
import base64, glob, os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
OUT = f'{ROOT}/composeApp/src/commonMain/kotlin/app/nocturne/ui/sound/SfxData.kt'
CHUNK = 60000

lines = ['package app.nocturne.ui.sound', '', '// Generated by tools/sounds/embed.py — do not edit.', 'internal object SfxData {']
for path in sorted(glob.glob(os.path.join(os.path.dirname(__file__), '*.wav'))):
    name = os.path.splitext(os.path.basename(path))[0]
    b = base64.b64encode(open(path, 'rb').read()).decode()
    parts = [b[i:i + CHUNK] for i in range(0, len(b), CHUNK)]
    lines.append(f'    val {name} = arrayOf(')
    lines += [f'        "{p}",' for p in parts]
    lines.append('    )')
lines.append('}')
open(OUT, 'w').write('\n'.join(lines) + '\n')
print(OUT)
