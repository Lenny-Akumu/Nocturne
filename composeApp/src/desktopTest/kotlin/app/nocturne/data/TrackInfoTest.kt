package app.nocturne.data

import app.nocturne.source.describe
import app.nocturne.ui.components.dayOf
import app.nocturne.ui.components.grouped
import app.nocturne.ui.components.releaseDate
import kotlin.test.Test
import kotlin.test.assertEquals

class TrackInfoTest {
    @Test
    fun providedToYouTubeDescription() {
        val desc = """
            Provided to YouTube by Universal Music Group

            Believer · Imagine Dragons

            Evolve

            ℗ 2017 KIDinaKORNER/Interscope Records

            Released on: 2017-06-23

            Producer: Mattman & Robin
            Composer Lyricist: Dan Reynolds
            Associated  Performer: Wayne Sermon

            Auto-generated by YouTube.
        """.trimIndent()
        val (released, label, credits) = describe(desc)
        assertEquals("2017-06-23", released)
        assertEquals("KIDinaKORNER/Interscope Records", label)
        assertEquals(listOf("Producer" to "Mattman & Robin", "Composer Lyricist" to "Dan Reynolds", "Associated Performer" to "Wayne Sermon"), credits)
        assertEquals(Triple(null, null, emptyList()), describe("Official video of Believer. Follow us: instagram"))
    }

    @Test
    fun formatting() {
        assertEquals("3 083 808 629", grouped(3_083_808_629))
        assertEquals("975 525", grouped(975_525))
        assertEquals("07.03.2017", releaseDate("2017-03-07T06:00:00-08:00"))
        assertEquals("03.2017", releaseDate("2017-03"))
        assertEquals("2017", releaseDate("2017"))
        assertEquals("27.11.2026", dayOf(1_795_780_800_000))
        assertEquals("01.01.1970", dayOf(0))
    }
}
