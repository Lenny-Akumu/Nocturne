// Pixel-art stand-ins for Material icons (Monocraft look). Keyed by ImageVector.name, e.g. "Rounded.PlayArrow".
private val Styles = setOf("Filled", "Rounded", "Outlined", "Sharp", "TwoTone")
private val Cache = HashMap<String, ImageVector?>()

fun pixelFor(v: ImageVector): ImageVector? = Cache.getOrPut(v.name) {
    val n = v.name.removePrefix("AutoMirrored.")
    if (n.substringBefore('.') !in Styles) return@getOrPut null
    val simple = n.substringAfter('.')
    val grid = Grids[n] ?: Grids[simple] ?: Alias[simple]?.let { Grids[it] } ?: return@getOrPut null
    build("Pixel.$n", grid, v.autoMirror)
}

// One path of rects: horizontal runs, stacked while identical across rows (no AA seams).
private fun build(name: String, grid: String, mirror: Boolean): ImageVector {
    val rows = grid.trim().lines().map { it.trim() }
    return ImageVector.Builder(name, 24.dp, 24.dp, 16f, 16f, autoMirror = mirror).path(fill = SolidColor(Color.Black)) {
        var open = HashMap<Pair<Int, Int>, Int>()
        for (y in 0..rows.size) {
            val next = HashMap<Pair<Int, Int>, Int>()
            val row = rows.getOrNull(y).orEmpty()
            var x = 0
            while (x < row.length) {
                if (row[x] != '#') { x++; continue }
                val s = x
                while (x < row.length && row[x] == '#') x++
                val r = s to x
                next[r] = open.remove(r) ?: y
            }
            for ((r, y0) in open) {
                moveTo(r.first.toFloat(), y0.toFloat()); horizontalLineTo(r.second.toFloat())
                verticalLineTo(y.toFloat()); horizontalLineTo(r.first.toFloat()); close()
            }
            open = next
        }
    }.build()
}

