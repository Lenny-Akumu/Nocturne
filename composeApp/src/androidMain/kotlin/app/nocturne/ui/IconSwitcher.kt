package app.nocturne.ui

import android.content.ComponentName
import android.content.pm.PackageManager
import android.os.Build
import androidx.compose.ui.graphics.Color
import app.nocturne.AndroidContext
import app.nocturne.data.IconBackground
import app.nocturne.data.IconPalette

actual fun systemIconColors(): IconColors? {
    if (Build.VERSION.SDK_INT < Build.VERSION_CODES.S) return null
    return runCatching {
        val ctx = AndroidContext.app
        fun c(id: Int) = Color(ctx.getColor(id))
        IconColors(
            c(android.R.color.system_accent1_200), c(android.R.color.system_accent1_500),
            c(android.R.color.system_accent1_100), c(android.R.color.system_accent1_400), c(android.R.color.system_accent1_600),
        )
    }.getOrNull()
}

private fun cap(s: String) = s.lowercase().replaceFirstChar { it.uppercase() }

// <activity-alias> names generated by tools/icons/gen_icons.py, e.g. app.nocturne.IconSquareStandard.
private fun alias(b: IconBackground, p: IconPalette) = "app.nocturne.Icon${cap(b.name)}${cap(p.name)}"

private val DEFAULT_ALIAS = alias(IconBackground.SQUARE, IconPalette.STANDARD)

actual fun applyAppIcon(background: IconBackground, palette: IconPalette) {
    runCatching {
        val ctx = AndroidContext.app
        val pm = ctx.packageManager
        val target = alias(background, palette)
        // Enable the target first so exactly one launcher entry always stays enabled.
        val all = listOf(target) + IconBackground.entries.flatMap { b -> IconPalette.entries.map { alias(b, it) } }.filter { it != target }
        all.forEach { name ->
            val cn = ComponentName(ctx, name)
            val want = if (name == target) PackageManager.COMPONENT_ENABLED_STATE_ENABLED else PackageManager.COMPONENT_ENABLED_STATE_DISABLED
            val now = pm.getComponentEnabledSetting(cn).let {
                if (it != PackageManager.COMPONENT_ENABLED_STATE_DEFAULT) it
                else if (name == DEFAULT_ALIAS) PackageManager.COMPONENT_ENABLED_STATE_ENABLED
                else PackageManager.COMPONENT_ENABLED_STATE_DISABLED
            }
            if (now != want) pm.setComponentEnabledSetting(cn, want, PackageManager.DONT_KILL_APP)
        }
    }
}
